//! Sample this machine's agent sessions and write anonymized fixtures.
//!
//! ```text
//! cargo run -p cormex-transcript --example sample_fixtures -- --out <dir>
//! ```
//!
//! Design: docs/plan/session-archive-plan.md P2-0.
//!
//! # What it does
//!
//! 1. Discovers this machine's session files through the same catalog the
//!    capture client uses, so "what counts as a session" has one answer
//! 2. Picks at most three per agent: the smallest, the median, and the one with
//!    the most distinct record types
//! 3. Truncates each to 2000 lines or 2 MiB, on a line boundary
//! 4. Anonymizes every JSON value, keeping structure and replacing free text
//! 5. **Scans the output** and aborts without writing anything if a leak is
//!    found
//! 6. Writes `<out>/<agent>/<name>.jsonl` and a `MANIFEST.md`
//!
//! # It is a dev tool, not a library function
//!
//! It needs the CLI's discovery and the memory crate's redaction rules, and
//! neither belongs in a parser's dependency tree. An `examples/` target is the
//! only place in cargo that gets those without them becoming dependencies of
//! the crate itself.

use std::collections::{BTreeMap, BTreeSet};
use std::io::Write as _;
use std::path::{Path, PathBuf};

use cormex_transcript::anonymize::{Anonymizer, RULES_VERSION};

/// How many lines of a session are kept.
const MAX_LINES: usize = 2000;

/// How many bytes of a session are kept.
const MAX_BYTES: usize = 2 << 20;

/// How many sessions per agent.
const MAX_PER_AGENT: usize = 3;

fn main() -> anyhow::Result<()> {
    let mut out: Option<PathBuf> = None;
    let mut args = std::env::args().skip(1);
    while let Some(a) = args.next() {
        match a.as_str() {
            "--out" => out = args.next().map(PathBuf::from),
            "--help" | "-h" => {
                println!("usage: sample_fixtures --out <dir>");
                return Ok(());
            }
            other => anyhow::bail!("unknown argument {other:?}; usage: --out <dir>"),
        }
    }
    let out = out.ok_or_else(|| anyhow::anyhow!("--out <dir> is required"))?;

    let catalog = cormex_proto::catalog::Catalog::builtin().clone();
    let cfg = cormex::config::Config::default();
    let files = cormex::catalog::discover(&catalog, &cfg, "fixture-sampler")?;

    if files.is_empty() {
        println!("no session files found on this machine");
        return Ok(());
    }

    // Group by agent
    let mut by_agent: BTreeMap<String, Vec<&cormex::catalog::DiscoveredFile>> = BTreeMap::new();
    for f in &files {
        by_agent.entry(f.agent.clone()).or_default().push(f);
    }

    let mut manifest = String::new();
    manifest.push_str("# Fixtures\n\n");
    manifest.push_str(&format!(
        "Generated by `cargo run -p cormex-transcript --example sample_fixtures`.\n\n\
         Anonymization rules: **{RULES_VERSION}**.\n\n\
         Every free-text value has been replaced with synthetic text of the same length and \
         character class. Ids are mapped consistently, so `parentUuid ↔ uuid` and \
         `tool_use_id ↔ tool_result` references still point at each other. Timestamps are \
         shifted by one constant, preserving order and format.\n\n"
    ));

    let shift = 86_400 * 365;
    let mut total_written = 0usize;

    for (agent, mut candidates) in by_agent {
        // The three picks: smallest, median, most distinct record types
        candidates.sort_by_key(|f| file_len(&f.physical_path));
        let smallest = 0;
        let median = candidates.len() / 2;
        let mut type_counts: Vec<(usize, usize)> = candidates
            .iter()
            .enumerate()
            .map(|(i, f)| (i, distinct_record_types(&f.physical_path)))
            .collect();
        type_counts.sort_by_key(|(_, n)| std::cmp::Reverse(*n));
        let most_varied = type_counts.first().map(|(i, _)| *i).unwrap_or(0);

        let picks: BTreeSet<usize> = [smallest, median, most_varied]
            .into_iter()
            .take(MAX_PER_AGENT)
            .collect();

        let dir = out.join(&agent);
        std::fs::create_dir_all(&dir)?;

        let mut agent_manifest = String::new();
        agent_manifest.push_str(&format!("## {agent}\n\n"));
        agent_manifest.push_str("- source: **real-derived** (sampled on this machine)\n");
        agent_manifest.push_str(&format!("- files sampled: {}\n\n", picks.len()));

        for idx in picks {
            let file = candidates[idx];
            let (body, lines, truncated) = read_capped(&file.physical_path)?;
            let name = format!("{}-{}", sanitize(&file.native_session_id), idx);
            let path = dir.join(format!("{name}.jsonl"));

            let (anonymized, types) = anonymize_lines(&body, shift)?;

            // ── The safety net ──
            //
            // Two scans, on two different things:
            //
            // - the **output**, for registered private strings and a home
            //   directory that is not the placeholder. A hit here aborts.
            // - the **input**, for email and IPv4 shapes. A hit there is
            //   informational: the anonymizer replaces them anyway, and
            //   scanning the output for those shapes would abort on every
            //   fixture that ever contained one, because the synthetic text
            //   keeps the character class.
            let mut leaks = Vec::new();
            for line in &anonymized {
                if let Some(hit) = redaction_hit(line) {
                    leaks.push(hit);
                }
            }
            if let Some(hit) = output_safety_net(&anonymized) {
                leaks.push(hit);
            }
            let input_hits = input_scan(&body);
            if !leaks.is_empty() {
                // **Abort without writing.** A fixture that leaks is in the git
                // history forever, and `.gitignore` cannot take it back
                anyhow::bail!(
                    "refusing to write {}: the anonymized output still contains {}",
                    path.display(),
                    leaks.join(", ")
                );
            }

            let mut f = std::fs::File::create(&path)?;
            for line in &anonymized {
                writeln!(f, "{line}")?;
            }

            agent_manifest.push_str(&format!(
                "- `{name}.jsonl`: {} lines{}, record types: {}\n",
                lines,
                if truncated { " (truncated)" } else { "" },
                types.iter().cloned().collect::<Vec<_>>().join(", ")
            ));
            if !input_hits.is_empty() {
                // Informational: the anonymizer already replaced these, and
                // saying so is what makes "I looked at the output" a claim
                // somebody can check
                agent_manifest.push_str(&format!(
                    "  - input contained {}; replaced by the anonymizer\n",
                    input_hits.join(", ")
                ));
            }
            total_written += 1;
        }
        agent_manifest.push('\n');
        manifest.push_str(&agent_manifest);
    }

    std::fs::write(out.join("MANIFEST.md"), manifest)?;
    println!("wrote {total_written} fixture(s) to {}", out.display());
    Ok(())
}

fn file_len(path: &Path) -> u64 {
    std::fs::metadata(path).map(|m| m.len()).unwrap_or(0)
}

/// How many distinct `type` values a file has.
///
/// Read for **selection only**, before anonymization: the file is about to be
/// read in full anyway, and "which file exercises the most record types" cannot
/// be answered from metadata.
fn distinct_record_types(path: &Path) -> usize {
    let Ok(body) = std::fs::read(path) else {
        return 0;
    };
    let mut types = BTreeSet::new();
    for line in body.split(|b| *b == b'\n').take(MAX_LINES) {
        if let Ok(v) = serde_json::from_slice::<serde_json::Value>(line)
            && let Some(t) = v.get("type").and_then(|t| t.as_str())
        {
            types.insert(t.to_owned());
        }
    }
    types.len()
}

/// Read a file, capped at [`MAX_LINES`] lines and [`MAX_BYTES`] bytes, on a
/// line boundary.
///
/// The cap is on a **line** boundary because half a JSON line is not a record;
/// the parser's handling of a split line is a separate test (P2-1's chunk
/// invariance), and a fixture that is itself truncated mid-line would test it
/// by accident.
fn read_capped(path: &Path) -> anyhow::Result<(Vec<u8>, usize, bool)> {
    let body = std::fs::read(path)?;
    let mut out = Vec::new();
    let mut lines = 0;
    let mut truncated = false;
    for line in body.split_inclusive(|b| *b == b'\n') {
        if lines >= MAX_LINES || out.len() + line.len() > MAX_BYTES {
            truncated = true;
            break;
        }
        out.extend_from_slice(line);
        lines += 1;
    }
    Ok((out, lines, truncated))
}

/// Anonymize each line, returning the lines and the record types seen.
fn anonymize_lines(
    body: &[u8],
    shift_secs: i64,
) -> anyhow::Result<(Vec<String>, BTreeSet<String>)> {
    let mut anon = Anonymizer::new(shift_secs);
    // This machine's own identifiers, so the safety net can look for them
    if let Ok(host) = std::env::var("HOSTNAME") {
        anon.forbid(&host);
    }
    if let Ok(user) = std::env::var("USER") {
        anon.forbid(&user);
    }
    if let Some(base) = directories::BaseDirs::new() {
        anon.forbid(&base.home_dir().display().to_string());
    }

    let mut out = Vec::new();
    let mut types = BTreeSet::new();
    for line in body.split(|b| *b == b'\n') {
        if line.is_empty() {
            continue;
        }
        match serde_json::from_slice::<serde_json::Value>(line) {
            Ok(v) => {
                if let Some(t) = v.get("type").and_then(|t| t.as_str()) {
                    types.insert(t.to_owned());
                }
                let anon_v = anon.value(None, &v);
                out.push(serde_json::to_string(&anon_v)?);
            }
            Err(_) => {
                // A line that is not JSON is kept as a synthetic string of the
                // same shape: the parser has to handle it, and dropping it
                // would hide that case
                out.push(serde_json::to_string(&serde_json::Value::String(
                    cormex_transcript::synthetic_text(&String::from_utf8_lossy(line)),
                ))?);
            }
        }
    }
    Ok((out, types))
}

/// Check the anonymized output for a home directory that is not the
/// placeholder.
///
/// The only output-side shape check that is meaningful: the placeholder is a
/// fixed string, so anything else is either a bug or a path that arrived
/// through a key this module does not know about.
fn output_safety_net(lines: &[String]) -> Option<String> {
    for line in lines {
        if let Some(idx) = line.find("/home/") {
            let rest = &line[idx + 6..];
            let name: String = rest
                .chars()
                .take_while(|c| *c != '/' && *c != '"' && *c != '\\')
                .collect();
            if !name.is_empty() && name != "user" {
                return Some("a home directory that is not the placeholder".to_owned());
            }
        }
    }
    None
}

/// Email and IPv4 shapes in the **input**.
fn input_scan(body: &[u8]) -> Vec<String> {
    let text = String::from_utf8_lossy(body);
    let mut hits = Vec::new();
    if text.split_whitespace().any(|w| {
        let w = w.trim_matches(|c: char| !c.is_alphanumeric() && c != '@' && c != '.' && c != '-');
        w.contains('@') && w.contains('.') && w.len() > 5
    }) {
        hits.push("an email address".to_owned());
    }
    if text
        .split(|c: char| !c.is_ascii_digit() && c != '.')
        .any(|w| {
            let parts: Vec<&str> = w.split('.').collect();
            parts.len() == 4
                && parts
                    .iter()
                    .all(|p| !p.is_empty() && p.len() <= 3 && p.parse::<u8>().is_ok())
        })
    {
        hits.push("an IPv4 address".to_owned());
    }
    hits
}

/// Run the memory crate's redaction scan over one line.
///
/// Returns the rule's name, never the matched text.
fn redaction_hit(line: &str) -> Option<String> {
    cormex_memory::redaction::scan(line).map(|rule| format!("a {} match", rule.name()))
}

/// A filename-safe version of a session id.
fn sanitize(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                c
            } else {
                '-'
            }
        })
        .take(64)
        .collect()
}
