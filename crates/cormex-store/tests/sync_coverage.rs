//! Every table that can enter `sync_log` must be recognized by `fetch_since`.
//!
//! # What this gate stops
//!
//! `load_payloads` dispatches on `match table_name`, with a final `other =>`
//! arm returning `UnknownTable`. When adding a new table it is very easy to
//! finish the "write side" and call it done — because that tests entirely
//! green: the new table can be written, can be queried, and the unit tests all
//! pass.
//!
//! Things only go wrong when **the first device comes to pull sync**:
//! `fetch_since` hits the unrecognized table name and the whole batch fails,
//! which is not "this table fails to sync" but rather that **every** change
//! after that cursor becomes unpullable, and the client is jammed from then on.
//! And that may happen weeks after release, by which point the new table has
//! many rows in it.
//!
//! So this test walks [`table::ALL`] (generated by the macro alongside the
//! constants, so adding a constant necessarily adds it to the list) and hits
//! them one by one. Whoever forgets the match arm **fails immediately**.
//!
//! # What it does not stop: **adding a column to an existing table**
//!
//! What gets inserted below are ids of rows that do not exist — the SELECT
//! returns an empty set every time, and sqlx only notices a missing column when
//! it actually has to decode a row. So a change like "added `diff` to
//! `episode_tool_calls`, updated the three SELECTs in `query.rs`, missed the
//! fourth one in `sync.rs`" is green here, and the failure is still a batch-wide
//! /sync 500 with a jammed cursor (which did happen once).
//!
//! What has to be pinned down when adding a column is a round trip **with a real
//! row**: see `tool_call_diff_survives_replay_and_the_length_guard_bites` in
//! `replay.rs`.

mod common;

use cormex_store::table;

#[tokio::test]
async fn every_synced_table_has_a_payload_loader() {
    let Some(db) = common::setup().await else {
        return;
    };

    // Insert one log row per table pointing at a row that does not exist. The
    // payload loader runs its SELECT as usual, finds nothing, and returns None
    // -- which is entirely normal (that is what a redacted record looks like).
    // The only case that can fail is a table with no dispatch arm at all.
    for name in table::ALL {
        db.exec_raw(format!(
            "INSERT INTO sync_log (table_name, record_id) \
             VALUES ('{name}', 'ZZZZZZZZZZZZZZZZZZZZZZZZZZ')"
        ))
        .await;
    }

    let got = db.store.fetch_since(0, 1000).await;

    let records = match got {
        Ok(records) => records,
        Err(err) => {
            db.cleanup().await;
            panic!(
                "some table name has no payload loading arm: {err}\n\
                 -- a table was added, the table constants were updated, but the match in \
                 sync.rs was missed. Left unfixed, every client's sync cursor jams permanently \
                 the first time this table is written."
            );
        }
    };

    assert_eq!(
        records.len(),
        table::ALL.len(),
        "every sync_log row should come back as one record; got {} records for {} tables",
        records.len(),
        table::ALL.len()
    );

    // While we are here, pin down "give None rather than an error when the row
    // is not found" -- that is the normal shape after a redaction, and if it
    // ever became an error, a database whose content has been redacted would
    // stop syncing entirely
    for r in &records {
        assert!(
            r.payload.is_none(),
            "a log row pointing at a nonexistent row should have an empty payload, not conjure \
             one out of thin air: {}",
            r.table_name
        );
    }

    db.cleanup().await;
}
