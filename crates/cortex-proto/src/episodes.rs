//! `POST /episodes` — the local agent writing one conversational turn back
//! into the memory store.
//!
//! # Why writing and retrieval are **one and the same** request
//!
//! The original design had two endpoints: `GET /memory/context` to fetch
//! memory, with episode writes going down a separate path. That does not work
//! — the attribution "which facts were injected this turn" is anchored on the
//! user episode (the `episode_memories` table, which is the sole source for the
//! "why do you remember this" drawer in the UI). Splitting it in two means the
//! client has to send the fact ids back for attribution: one more round trip,
//! and **attribution becomes whatever the client says it is** — it can
//! under-report or mis-report, with no way to check.
//!
//! Merged into one, retrieval and attribution happen in the same piece of
//! server-side code, and the client receives the result.
//!
//! # Why the response is structured data rather than a rendered memory block
//!
//! Rendering stays local, via the shared [`cortex_core::injection`]. The
//! reasoning is in that module's comments: have the endpoint return text and
//! format drift **raises no error**; return structured data and drift is a JSON
//! deserialization failure that blows up on the spot.
//!
//! # The id is generated by the client
//!
//! ULID was designed for exactly this (globally unique, time-ordered, no
//! coordination needed between endpoints). The client has to have an id before
//! it can queue a turn locally while **offline** and replay it once back on the
//! network — and replay requires server-side idempotence, see
//! [`EpisodeAck::already_existed`].

use serde::{Deserialize, Serialize};

use crate::dto::{AttachmentRef, FactDto};

/// The attribution of one tool call — the upstream direction.
///
/// Kept separate from `dto::ToolCallDto`, which is used for replay: that one is
/// the downstream display form (no `ordinal`, because ordering is expressed by
/// array position), while this one lands in the `episode_tool_calls` table.
/// Merging them into one type would force one side to carry fields it does not
/// need, and the values of those fields then become "anything goes" — leaving
/// the next person to read the code no way to tell which one is real.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCallInput {
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
    pub summary: String,
    pub ok: bool,
    /// What this write changed (unified diff, already truncated). See `diff` on
    /// `dto::ChatEvent::Tool`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub diff: Option<String>,
}

/// The request body of `POST /episodes`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NewEpisodeRequest {
    /// **A client-generated ULID.** The idempotency key; see the module
    /// comments.
    pub id: String,
    pub session_id: String,
    /// `user` / `assistant`. The server accepts only these two — `tool` and
    /// `system` are not "a conversational turn"; they are expressed by tool
    /// attribution and the system prompt respectively.
    pub role: String,
    pub text: String,
    /// When this turn **actually happened**, RFC 3339.
    ///
    /// Supplied by the client rather than taken from the server's `now()`: turns
    /// queued offline may only get flushed back hours later, and using the
    /// moment of persistence would shift the whole timeline — while the memory
    /// system's bitemporal design exists precisely to separate "when it
    /// happened" from "when it became known". The system-time half is still
    /// recorded by the server's `created_at`, which the client cannot touch.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub occurred_at: Option<String>,
    /// Attachments. The hashes must be **already registered** blobs; the server
    /// only creates the association.
    #[serde(default)]
    pub attachments: Vec<AttachmentRef>,
    /// Whether to run a memory retrieval along the way. Only meaningful for
    /// `role = user`.
    ///
    /// Set false when replaying offline turns: that turn's memory should have
    /// been injected and was not, and retrieving now is both late and untrue
    /// (it would record "things learned afterwards" as "things injected at the
    /// time", making the attribution a lie).
    #[serde(default)]
    pub retrieve: bool,
    /// The **user episode id** of this turn. Should be present when
    /// `role = assistant`.
    ///
    /// It settles two things at once:
    ///
    /// 1. **Where tool attribution is anchored** — on the user row, not the
    ///    assistant one (see migration 20260807000005). When the model errors
    ///    out, the assistant row never lands in the database at all, and yet
    ///    the tools really did run.
    /// 2. **Which two utterances extraction pairs up** — the server uses it to
    ///    read the user's original text back, splices it together with this
    ///    request's `text` into one turn, and feeds that to the extraction
    ///    pipeline. The client is not asked to send the user text a second time:
    ///    one sentence with two sources creates a "the two disagree" path that
    ///    has to be handled, and the copy in the database is the authoritative
    ///    one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub anchor_episode_id: Option<String>,
    #[serde(default)]
    pub tool_calls: Vec<ToolCallInput>,
}

/// The response of `POST /episodes`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EpisodeAck {
    pub episode_id: String,
    /// Which memories to inject for this turn. Empty when `retrieve = false`.
    ///
    /// **Not rendered text** — rendering happens locally, see the module
    /// comments.
    #[serde(default)]
    pub memories: Vec<FactDto>,
    /// This id had already been written; this request was a no-op.
    ///
    /// Replaying an offline queue inevitably delivers duplicates (a crash
    /// between "the server accepted it" and "the local side recorded it as
    /// flushed" means another attempt). Returning true rather than 409:
    /// duplicate delivery is a normal, **expected** path, and an error would
    /// force clients to handle a normal outcome as an exception — in a piece of
    /// code that never runs day to day and gets executed for the first time
    /// only when something actually goes wrong.
    #[serde(default)]
    pub already_existed: bool,
}
