-- Projects: grouping containers for sessions
--
-- [Why another event table, instead of an UPDATE-able projects table]
--
-- The same reason as session_events (see the header of 20260807000002): append-only end to
-- end, so a rename appends a rename event rather than editing a field in place. Concurrent
-- renames on several devices replay in sync_log's total order and every device computes the
-- same final state; under UPDATE semantics it is "whoever arrives last wins", and each of
-- the two devices is convinced it arrived last.
--
-- [Why only the three ops create / rename / delete, and no archive]
--
-- A project is a lightweight grouping to begin with, and its contents (sessions and
-- memories) already have their own two roads, archiving and erasure. Putting another layer
-- of "archived projects" on the container would mean one more filter in the UI -- and
-- nobody would use that filter: someone who wants to put a project away reaches for
-- delete, not archive.
-- One state dimension fewer is also one whole class of combined semantics fewer -- the
-- kind that has to be spelled out at every single site, such as "the project is archived
-- but the sessions inside it are still in the default list".
--
-- [What delete removes is the grouping, not the contents]
--
-- delete is a tombstone event: the project disappears from the list and the sessions inside
-- it become **ungrouped** (in session_state a binding that points at a deleted project is
-- treated as NULL, see the EXISTS clause in the view below), while sessions, messages,
-- attachments and already-extracted facts are all left untouched. This is the same restraint
-- as "archiving a session": the only thing that genuinely destroys content is redact /
-- purge in redactions, a road that has to be taken explicitly, confirmed twice, and leaves
-- a tombstone (docs/memory.md §11).
--
-- Deliberately **not** cascading a batch of remove_from_project events on delete: that
-- would be N writes, and it does not match the intent of "the user merely wanted to put
-- this grouping away" -- should it turn out to be a mistaken delete, a create event with
-- the same id brings every session back exactly as it was. Once the cascade is written,
-- there is no way back.

CREATE TABLE project_events (
    id          ulid        PRIMARY KEY,

    -- Same origin as session_events.session_id: there is no projects table, so there is no
    -- foreign key, and the id is generated by the client. Creating a project that contains
    -- no sessions at all is allowed -- the user creating a project and then dragging
    -- sessions into it is the most natural order
    project_id  TEXT        NOT NULL,

    -- Two state machines (see the project_state view):
    --   create / delete → whether it exists
    --   create / rename → its current name
    -- create is the starting point of both machines, which is why it appears on both sides
    op          TEXT        NOT NULL CHECK (op IN ('create', 'rename', 'delete')),

    -- The name, when op = create / rename
    name        TEXT,

    actor       TEXT        NOT NULL CHECK (actor IN ('system', 'user')),
    device_id   TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    -- Both directions have to be stated, same reason as in session_events: writing only
    -- "create must have a name" would let dirty data like "delete carrying a name" through,
    -- and in the view that shows up as "deleting it also changed the name"
    CHECK (op =  'delete' OR name IS NOT NULL),
    CHECK (op <> 'delete' OR name IS NULL),

    -- The caps are defensive: name and id both come from the client, and with no cap a
    -- 10 MB "project name" would go into sync_log and be shipped to every device
    CHECK (name IS NULL OR (length(name) BETWEEN 1 AND 100)),
    CHECK (length(project_id) BETWEEN 1 AND 64)
);

COMMENT ON TABLE project_events IS
    'Project lifecycle events (append-only). A project is a grouping container for sessions,
     and deleting it only dissolves the grouping: the sessions inside become ungrouped, and
     messages and derived memory are left completely untouched.
     What genuinely destroys content is redact / purge in redactions -- different meaning,
     and it should not share one button in the UI.';

-- Aligned with the ordering of the two DISTINCT ONs in the project_state view
CREATE INDEX idx_project_events ON project_events (project_id, created_at DESC);
CREATE INDEX idx_project_events_op ON project_events (op, project_id, created_at DESC);

-- ══════════════════════════════════════════════════════════
--  project_state -- the projects that exist, and their current names
--
--  [Why existence needs a state machine of its own]
--
--  The same shape as session_state: the last row of the sequence [create, delete, rename]
--  is rename, yet the project has already been deleted. "The last row in the whole table"
--  is a wrong criterion on any multi-dimensional event table.
--
--  The ordering (created_at DESC, id DESC) matches session_state / fact_status:
--  created_at is the microsecond value of clock_timestamp(), and id (a ULID,
--  byte-comparable under COLLATE "C") is only a deterministic tiebreaker at the extreme
--  same instant -- without it, two devices renaming inside the same microsecond would let
--  different replicas compute different names, and that kind of inconsistency neither
--  raises an error nor converges.
-- ══════════════════════════════════════════════════════════

CREATE VIEW project_state AS
WITH last_name AS (
    SELECT DISTINCT ON (project_id) project_id, name
      FROM project_events WHERE op IN ('create', 'rename')
     ORDER BY project_id, created_at DESC, id DESC
),
last_life AS (
    SELECT DISTINCT ON (project_id) project_id, op, created_at
      FROM project_events WHERE op IN ('create', 'delete')
     ORDER BY project_id, created_at DESC, id DESC
)
SELECT l.project_id,
       n.name,
       -- The last lifecycle event is that create, so its time is "when it was created".
       -- The first create is deliberately not taken instead: after a re-creation under the
       -- same id (undoing a mistaken delete), the creation time in the user's mind is the
       -- moment of that re-creation, not the time of an old project that no longer ever existed
       l.created_at
  FROM last_life l
  -- An inner join rather than a left one: a living project necessarily has that create, and
  -- a create always carries a name. Writing LEFT JOIN would only make callers write a
  -- branch for a NULL that cannot occur
  JOIN last_name n ON n.project_id = l.project_id
 -- Only "the last lifecycle event is a create" counts as existing.
 -- Writing l.op <> 'delete' would be equivalent, but this states the criterion more plainly
 WHERE l.op = 'create';

-- ══════════════════════════════════════════════════════════
--  Session side: the fourth dimension
-- ══════════════════════════════════════════════════════════

-- Which project it belongs to. NULL = ungrouped
ALTER TABLE session_events ADD COLUMN project_id TEXT;

-- The old op allowlist has no room for the two new actions. **No IF EXISTS**: if the name
-- does not match, the migration should fail on the spot -- the consequence of silently
-- keeping the old constraint is that the "move into project" action gets rejected by the
-- database at runtime, by which time the code has long since been released
ALTER TABLE session_events DROP CONSTRAINT session_events_op_check;
ALTER TABLE session_events ADD CONSTRAINT session_events_op_check CHECK (op IN (
    'rename', 'archive', 'unarchive',
    'bind_workspace', 'unbind_workspace',
    'move_to_project', 'remove_from_project'));

-- Each op may carry only its own payload field, stated in both directions (the reason given
-- for the other CHECKs in this table)
ALTER TABLE session_events ADD CONSTRAINT session_events_project_required
    CHECK (op <> 'move_to_project' OR project_id IS NOT NULL);
ALTER TABLE session_events ADD CONSTRAINT session_events_project_absent
    CHECK (op =  'move_to_project' OR project_id IS NULL);
ALTER TABLE session_events ADD CONSTRAINT session_events_project_id_len
    CHECK (project_id IS NULL OR (length(project_id) BETWEEN 1 AND 64));

-- ══════════════════════════════════════════════════════════
--  session_state -- rebuilt, with the fourth state machine added
--
--  The four dimensions remain mutually independent: after [move_to_project, archive] the
--  session is both inside a project and archived. The last row in the whole table is still
--  not the final state of any single dimension.
-- ══════════════════════════════════════════════════════════

DROP VIEW session_state;

CREATE VIEW session_state AS
WITH known AS (
    SELECT DISTINCT session_id FROM session_events
),
last_title AS (
    SELECT DISTINCT ON (session_id) session_id, title, created_at
      FROM session_events WHERE op = 'rename'
     ORDER BY session_id, created_at DESC, id DESC
),
last_archive AS (
    SELECT DISTINCT ON (session_id) session_id, op, created_at
      FROM session_events WHERE op IN ('archive', 'unarchive')
     ORDER BY session_id, created_at DESC, id DESC
),
last_workspace AS (
    SELECT DISTINCT ON (session_id) session_id, op, workspace, created_at
      FROM session_events WHERE op IN ('bind_workspace', 'unbind_workspace')
     ORDER BY session_id, created_at DESC, id DESC
),
last_project AS (
    SELECT DISTINCT ON (session_id) session_id, op, project_id, created_at
      FROM session_events WHERE op IN ('move_to_project', 'remove_from_project')
     ORDER BY session_id, created_at DESC, id DESC
)
SELECT k.session_id,
       t.title,
       coalesce(a.op = 'archive', false)                            AS archived,
       CASE WHEN w.op = 'bind_workspace' THEN w.workspace END       AS workspace,
       -- A binding that points at a **deleted project** is treated as ungrouped.
       --
       -- The judgement lives in the view instead of being written out again by every
       -- caller: deleting a project deliberately does not cascade into rewriting the
       -- sessions (see the header), so a "dangling project_id" is the normal case rather
       -- than an anomaly. Leaving it out in one place means the session list shows a
       -- grouping label for a project that does not exist, and clicking it shows nothing --
       -- and that one place is certain to be some newly added query, not this one
       CASE WHEN p.op = 'move_to_project'
             AND EXISTS (SELECT 1 FROM project_state ps
                          WHERE ps.project_id = p.project_id)
            THEN p.project_id END                                   AS project_id,
       -- GREATEST ignores NULL in Postgres, so this is NULL only when all four dimensions
       -- have no events at all -- and such a session never appears in known
       greatest(t.created_at, a.created_at, w.created_at, p.created_at) AS decided_at
  FROM known k
  LEFT JOIN last_title     t ON t.session_id = k.session_id
  LEFT JOIN last_archive   a ON a.session_id = k.session_id
  LEFT JOIN last_workspace w ON w.session_id = k.session_id
  LEFT JOIN last_project   p ON p.session_id = k.session_id;
