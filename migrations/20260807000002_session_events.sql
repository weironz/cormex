-- Session lifecycle: rename, archive, workspace binding
--
-- [Why a table of its own, instead of stuffing control records into episodes]
--
-- A rename has to keep a title the user supplied, an archive has to keep a state, a
-- workspace binding has to keep a path -- none of the three is a "raw message". Faking
-- them with episodes means opening a control channel inside the L0 raw layer, and L0's
-- contract is "raw messages, preserved losslessly": from then on fact extraction treats
-- them as source material, the time-recency leg of retrieval hits them, /sync ships them
-- to all three clients, and every client has to learn to recognize them and skip them.
-- The cost of one migration gets amortized into permanent complexity. See docs/memory.md §4.
--
-- [Why an event stream, instead of an UPDATE-able sessions table]
--
-- Append-only end to end (CLAUDE.md constraint 1). A rename is not an in-place edit of a
-- field but an appended rename event; the final state is decided by the last event of the
-- same kind -- the very state machine fact_events uses. That way concurrent renames on
-- several devices do not overwrite each other into an intermediate state nobody ever
-- wrote: replay in sync_log's total order and every device arrives at the same final state.

CREATE TABLE session_events (
    id          ulid        PRIMARY KEY,

    -- There is no sessions table, so there is no foreign key either. session_id has the
    -- same origin as episodes.session_id and is generated by the client. Writing an event
    -- for a session that has no messages yet is deliberately allowed: creating a session
    -- in the UI, picking a workspace first, and only then sending the first line is the
    -- most natural order.
    session_id  TEXT        NOT NULL,

    -- Three mutually independent dimensions, each of them a state machine of its own
    -- (see the session_state view):
    --   rename                            → title
    --   archive / unarchive               → archived
    --   bind_workspace / unbind_workspace → workspace
    -- Merged into one table rather than three: they share the single notion of "the
    -- session's final state", and splitting them would turn session_state into a
    -- three-way UNION for exactly zero gain.
    op          TEXT        NOT NULL CHECK (op IN (
                    'rename', 'archive', 'unarchive',
                    'bind_workspace', 'unbind_workspace')),

    -- The new title, when op = rename
    title       TEXT,
    -- Absolute path of a local directory, when op = bind_workspace.
    -- The server must validate it before writing (exists, is a directory, is not a system
    -- directory), see cortexd.
    -- A path is a **local-machine** notion: when multi-device sync ships this row, the
    -- same path may not exist at all on the other device -- a client should read it as
    -- "the binding on this machine", and treat a missing path as not bound.
    workspace   TEXT,

    actor       TEXT        NOT NULL CHECK (actor IN ('system', 'user')),
    device_id   TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    -- Each op may carry only its own payload field. Both directions have to be stated:
    -- writing just "rename must have a title" would let dirty data like "archive carrying
    -- a title" through, and dirty data shows up in the view as "archiving it also changed
    -- the title", which is exceedingly hard to trace back.
    CHECK (op <> 'rename' OR title IS NOT NULL),
    CHECK (op =  'rename' OR title IS NULL),
    CHECK (op <> 'bind_workspace' OR workspace IS NOT NULL),
    CHECK (op =  'bind_workspace' OR workspace IS NULL),

    -- The caps are defensive: title and path both come from the client, and with no cap a
    -- 10 MB "title" would go into sync_log and be shipped to every device
    CHECK (title IS NULL OR (length(title) BETWEEN 1 AND 200)),
    CHECK (workspace IS NULL OR (length(workspace) BETWEEN 1 AND 4096))
);

COMMENT ON TABLE session_events IS
    'Session lifecycle events (append-only). Archiving ≠ deleting: archiving only hides
     the session from the default list, messages and derived memory are left completely
     untouched, and unarchive restores it at any time. What actually destroys content is
     redact / purge in the redactions table -- the one operation in the whole system
     allowed to break append-only, which must be triggered explicitly, confirmed twice,
     and leave a tombstone (docs/memory.md §11).
     The two mean different things, and should not share one button in the UI.';

-- Aligned with the ordering of the session_state view (same idea as idx_fact_events)
CREATE INDEX idx_session_events ON session_events (session_id, created_at DESC);
-- The view takes the last row per dimension by op, and a full table scan there is linear
-- in the number of sessions; this index lets each dimension do one ordered scan of its own
CREATE INDEX idx_session_events_op ON session_events (op, session_id, created_at DESC);

-- ══════════════════════════════════════════════════════════
--  session_state -- the current final state of every session
--
--  [Why not one DISTINCT ON (session_id)]
--
--  The three dimensions are independent, so "the last event in the whole table" is not
--  the final state of any single one of them: the last row of the sequence
--  [archive, rename] is rename, yet the session is still archived.
--  So each dimension takes its own last row, and the results are stitched together.
--
--  The ordering (created_at DESC, id DESC) matches fact_status: created_at is the
--  microsecond value of clock_timestamp(), and id (a ULID, byte-comparable under
--  COLLATE "C") is only a deterministic tiebreaker for the extreme same-instant case --
--  without it, two devices renaming within the same microsecond would let different
--  replicas compute different titles, and that kind of inconsistency neither raises an
--  error nor converges.
-- ══════════════════════════════════════════════════════════

CREATE VIEW session_state AS
WITH known AS (
    SELECT DISTINCT session_id FROM session_events
),
last_title AS (
    SELECT DISTINCT ON (session_id) session_id, title, created_at
      FROM session_events WHERE op = 'rename'
     ORDER BY session_id, created_at DESC, id DESC
),
last_archive AS (
    SELECT DISTINCT ON (session_id) session_id, op, created_at
      FROM session_events WHERE op IN ('archive', 'unarchive')
     ORDER BY session_id, created_at DESC, id DESC
),
last_workspace AS (
    SELECT DISTINCT ON (session_id) session_id, op, workspace, created_at
      FROM session_events WHERE op IN ('bind_workspace', 'unbind_workspace')
     ORDER BY session_id, created_at DESC, id DESC
)
SELECT k.session_id,
       t.title,
       -- Never having had an archive event = not archived. coalesce rather than a bare
       -- comparison: NULL would make WHERE NOT archived filter all of those sessions out
       coalesce(a.op = 'archive', false)                            AS archived,
       CASE WHEN w.op = 'bind_workspace' THEN w.workspace END       AS workspace,
       -- GREATEST ignores NULL in Postgres, so this is NULL only when all three
       -- dimensions have no events at all -- and such a session never appears in known
       greatest(t.created_at, a.created_at, w.created_at)           AS decided_at
  FROM known k
  LEFT JOIN last_title     t ON t.session_id = k.session_id
  LEFT JOIN last_archive   a ON a.session_id = k.session_id
  LEFT JOIN last_workspace w ON w.session_id = k.session_id;
